CREATE TABLE IF NOT EXISTS tb_users
(
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY ( INCREMENT 1 START 1 MINVALUE 1 MAXVALUE 9223372036854775807 CACHE 1 ),
    name character varying(255) COLLATE pg_catalog."default" NOT NULL,
    username character varying(255) COLLATE pg_catalog."default" NOT NULL,
    password character varying(255) COLLATE pg_catalog."default" NOT NULL,
    is_active boolean NOT NULL,
    notify_chat_sounds boolean NOT NULL,
    notify_store_order boolean NOT NULL,
    role character varying(255) COLLATE pg_catalog."default",
    CONSTRAINT tb_users_pkey PRIMARY KEY (id),
    CONSTRAINT tb_users_username_key UNIQUE (username),
    CONSTRAINT tb_users_role_check CHECK (role::text = ANY (ARRAY['ADMIN'::character varying, 'SELLER'::character varying, 'LOGISTICS'::character varying]::text[]))
);

