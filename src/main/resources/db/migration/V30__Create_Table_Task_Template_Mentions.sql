CREATE TABLE IF NOT EXISTS tb_task_template_mentions
(
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY ( INCREMENT 1 START 1 MINVALUE 1 MAXVALUE 9223372036854775807 CACHE 1 ),
    task_template_id bigint NOT NULL,
    group_id bigint NOT NULL,
    placeholder character varying(255) COLLATE pg_catalog."default" NOT NULL,
    CONSTRAINT tb_task_template_mentions_pkey PRIMARY KEY (id),
    CONSTRAINT fk_task_template_mentions_template FOREIGN KEY (task_template_id)
        REFERENCES tb_task_templates (id) MATCH SIMPLE
        ON UPDATE NO ACTION
        ON DELETE CASCADE,
    CONSTRAINT fk_task_template_mentions_group FOREIGN KEY (group_id)
        REFERENCES tb_groups (id) MATCH SIMPLE
        ON UPDATE NO ACTION
        ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS tb_task_template_mention_users
(
    mention_id bigint NOT NULL,
    user_id bigint NOT NULL,
    PRIMARY KEY (mention_id, user_id),
    CONSTRAINT fk_mention_users_mention FOREIGN KEY (mention_id)
        REFERENCES tb_task_template_mentions (id) MATCH SIMPLE
        ON UPDATE NO ACTION
        ON DELETE CASCADE,
    CONSTRAINT fk_mention_users_user FOREIGN KEY (user_id)
        REFERENCES tb_users (id) MATCH SIMPLE
        ON UPDATE NO ACTION
        ON DELETE CASCADE
);
