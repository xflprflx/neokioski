CREATE TABLE IF NOT EXISTS tb_task_field_definitions
(
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY ( INCREMENT 1 START 1 MINVALUE 1 MAXVALUE 9223372036854775807 CACHE 1 ),
    description character varying(255) COLLATE pg_catalog."default" NOT NULL,
    input_type character varying(255) COLLATE pg_catalog."default",
    label character varying(255) COLLATE pg_catalog."default" NOT NULL,
    CONSTRAINT tb_task_field_definitions_pkey PRIMARY KEY (id),
    CONSTRAINT tb_task_field_definitions_input_type_check CHECK (input_type::text = ANY (ARRAY['TEXT'::character varying, 'NUMBER'::character varying, 'RADIO'::character varying, 'CHECKBOX'::character varying, 'DATE'::character varying, 'TIME'::character varying, 'DROPDOWN'::character varying, 'TEXT_LIST'::character varying, 'MULTISELECT_DROPDOWN'::character varying]::text[]))
);