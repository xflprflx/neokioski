CREATE TABLE IF NOT EXISTS tb_task_templates
(
    play_alert_sound boolean NOT NULL,
    registra_no_relatorio_loja boolean NOT NULL,
    requires_signature boolean NOT NULL,
    show_send_button boolean NOT NULL,
    sort_order integer NOT NULL,
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY ( INCREMENT 1 START 1 MINVALUE 1 MAXVALUE 9223372036854775807 CACHE 1 ),
    alert_sound character varying(255) COLLATE pg_catalog."default",
    default_responsible_role character varying(255) COLLATE pg_catalog."default",
    name character varying(255) COLLATE pg_catalog."default" NOT NULL,
    CONSTRAINT tb_task_templates_pkey PRIMARY KEY (id),
    CONSTRAINT tb_task_templates_name_key UNIQUE (name),
    CONSTRAINT tb_task_templates_default_responsible_role_check CHECK (default_responsible_role::text = ANY (ARRAY['ADMIN'::character varying, 'SELLER'::character varying, 'LOGISTICS'::character varying]::text[]))
);